package com.mystudentguide.entity;

import jakarta.persistence.*;
import lombok.*;

import java.time.LocalDate;

import java.util.ArrayList;
import java.util.List;

import com.mystudentguide.enums.DemarcheStatus;

/**
 * Represents an administrative procedure that an international
 * student may need to complete in France.
 *
 * A procedure is associated with:
 * - one StudentProfile
 * - one Categorie
 *
 * Example:
 * - Apply for health insurance
 * - Apply for housing assistance
 * - Open a bank account
 * - Validate a visa
 */
@Entity
@Table(name = "demarches")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class Demarche {

    /**
     * Unique identifier of the procedure.
     *
     * The value is automatically generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Title of the procedure.
     *
     * Example:
     * "Faire sa demande de Sécurité sociale"
     */
    @Column(nullable = false, length = 150)
    private String titre;

    /**
     * Detailed description of the procedure.
     *
     * This text explains to the student what the procedure
     * is and why it may be necessary.
     */
    @Column(nullable = false, columnDefinition = "TEXT")
    private String description;

    /**
     * Current status of the procedure.
     *
     * The actual type will be defined later through
     * the DemarcheStatus enum.
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 30)
    private DemarcheStatus statut;

    /**
     * Date on which the procedure was created
     * or assigned to the student.
     */
    @Column(nullable = false)
    private LocalDate dateCreation;

    /**
     * Optional deadline associated with the procedure.
     *
     * Some procedures do not have a specific deadline,
     * therefore this field can remain null.
     */
    private LocalDate dateLimite;

    /**
     * Indicates whether the procedure has been completed.
     *
     * This field may seem redundant with "statut".
     *
     * For now, we are keeping the status as the main
     * source of information. This boolean can therefore
     * be removed if we decide that it is unnecessary.
     */
    @Column(nullable = false)
    @Builder.Default
    private Boolean terminee = false;

    /**
     * Student profile associated with this procedure.
     *
     * One student profile can have several procedures.
     *
     * Example:
     *
     * StudentProfile
     *       |
     *       | 1
     *       |
     *       | *
     *       ▼
     *    Demarche
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "student_profile_id", nullable = false)
    private StudentProfile studentProfile;

    /**
     * Category associated with the procedure.
     *
     * Several procedures can belong to the same category.
     *
     * Example:
     *
     * Categorie: "Santé"
     *       |
     *       ├── Demarche 1
     *       ├── Demarche 2
     *       └── Demarche 3
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "categorie_id", nullable = false)
    private Categorie categorie;


    /**
 * Documents associés à cette démarche.
 *
 * Une démarche peut avoir plusieurs documents.
 */
@OneToMany(mappedBy = "demarche")
@Builder.Default
private List<Document> documents = new ArrayList<>();

}